-- Regression fixtures use real sale evidence. Every fixture change is rolled back.
begin;
do $$
declare who text:='sniper-game-regression-'||gen_random_uuid(); s public.sniper_sales%rowtype; token uuid:=gen_random_uuid(); w uuid:=gen_random_uuid(); a jsonb; refused boolean;
begin
 select * into s from public.sniper_sales where confirmed=true and price_usd>105 and price_usd<1600 limit 1;
 if s.id is null then raise exception 'A real recorded sale is required'; end if;
 a:=public.sniper_game_action(who,'state');
 if (a->>'cash')::numeric<>10000 then raise exception 'Starting balance'; end if;
 perform public.sniper_game_action(who,'offer',token,null,jsonb_build_object('itemId','regression-loss','title',s.series,'mode','historical','saleId',s.id,'durationMs',60000,'opening',1));
 a:=public.sniper_game_action(who,'bid',token,104);
 if (a->>'reserved')::numeric<>104 or (a->>'cash')::numeric<>10000 then raise exception 'Reservation'; end if;
 a:=public.sniper_game_action(who,'bid',token,105);
 if (a->>'reserved')::numeric<>105 then raise exception 'Raise must replace, not accumulate'; end if;
 refused:=false;
 begin perform public.sniper_game_action(who,'bid',token,10001); exception when others then refused:=true; end;
 if not refused then raise exception 'Overspend accepted'; end if;
 update public.sniper_paper_orders set game_deadline=clock_timestamp()-interval '1 second' where game_token=token;
 refused:=false;
 begin perform public.sniper_game_action(who,'bid',token,106); exception when others then refused:=true; end;
 if not refused then raise exception 'Late bid accepted'; end if;
 a:=public.sniper_game_action(who,'settle',token);
 if (a->>'cash')::numeric<>9895 or (a->>'reserved')::numeric<>0 then raise exception 'Losing charge'; end if;
 a:=public.sniper_game_action(who,'settle',token);
 if (a->>'cash')::numeric<>9895 then raise exception 'Duplicate settlement'; end if;
 perform public.sniper_game_action(who,'offer',w,null,jsonb_build_object('itemId','regression-win','title',s.series,'mode','historical','saleId',s.id,'durationMs',60000,'opening',1,'reference',106,'referenceSource','Independent valuation fixture; transaction rolls back'));
 perform public.sniper_game_action(who,'bid',w,1600);
 perform public.sniper_game_action(who,'refresh');
 if not exists(select 1 from public.sniper_paper_orders where game_token=w and status='bidding') then raise exception 'Refresh removed an active round'; end if;
 update public.sniper_paper_orders set game_deadline=clock_timestamp()-interval '1 second' where game_token=w;
 a:=public.sniper_game_action(who,'settle',w);
 if (a->>'cash')::numeric<>8295 then raise exception 'Winning cost'; end if;
 if not exists(select 1 from public.sniper_paper_orders where game_token=w and status='won' and fill_price_usd=1600 and fmv_usd=106) then raise exception 'Ownership or independent value'; end if;
 a:=public.sniper_game_action(who,'sell',w);
 if (a->>'cash')::numeric<>8401 then raise exception 'Overpayment inflated bank value'; end if;
 refused:=false;
 begin perform public.sniper_game_action(who,'sell',w); exception when others then refused:=true; end;
 if not refused then raise exception 'Duplicate redemption'; end if;
 if has_function_privilege('anon','public.sniper_game_action(text,text,uuid,numeric,jsonb,boolean)','EXECUTE') or has_function_privilege('authenticated','public.sniper_game_snapshot(text,boolean)','EXECUTE') then raise exception 'Private RPC access'; end if;
 who:=who||'-bonus'; token:=gen_random_uuid();
 perform public.sniper_game_action(who,'state');
 update public.sniper_paper_accounts set wins=5 where owner=who;
 perform public.sniper_game_action(who,'offer',token,null,jsonb_build_object('itemId','regression-bonus','title',s.series,'mode','historical','saleId',s.id,'durationMs',60000,'opening',1,'reference',106));
 perform public.sniper_game_action(who,'bid',token,1600);
 update public.sniper_paper_orders set game_deadline=clock_timestamp()-interval '1 second' where game_token=token;
 perform public.sniper_game_action(who,'settle',token);
 a:=public.sniper_game_action(who,'sell',token,null,null,true);
 if (a->>'cash')::numeric<>8612 or (a->>'doubleDowns')::numeric<>0 then raise exception 'Double Down value or consumption'; end if;
 who:=who||'-buy'; token:=gen_random_uuid();
 select * into s from public.sniper_sales where confirmed=true and price_usd>0 and price_usd<106 limit 1;
 if s.id is null then raise exception 'Low-price real sale required'; end if;
 perform public.sniper_game_action(who,'offer',token,null,jsonb_build_object('itemId','regression-bargain','title',s.series,'mode','historical','saleId',s.id,'durationMs',60000,'opening',1,'reference',212));
 perform public.sniper_game_action(who,'bid',token,106);
 update public.sniper_paper_orders set game_deadline=clock_timestamp()-interval '1 second' where game_token=token;
 perform public.sniper_game_action(who,'settle',token);
 a:=public.sniper_game_action(who,'sell',token);
 if (a->>'cash')::numeric<>10106 then raise exception 'Profitable capture accounting'; end if;
end $$;
select 'PASS: reserve, raise, overspend, late bid, loss, win, refresh, idempotence, underwater resale, Double Down, profitable capture and access' as verification;
rollback;
